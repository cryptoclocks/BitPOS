#!/usr/bin/env python3
"""Reviewed U35/U36/U37 shared presentation geometry, no business facts."""
import argparse,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 sha=hashlib.sha256((ROOT/'design/figcraft/BitPOS-Platform-UI.figcraft').read_bytes()).hexdigest()
 docs={s:json.loads((ROOT/f'design/figcraft/reports/layout-ir/{s}.json').read_text()) for s in ['U35','U36','U37']}
 def one(screen,kind,box):
  doc=docs[screen]
  if doc['masterSha256']!=sha:raise SystemExit('Stale commerce IR: '+screen)
  found=[n for n in doc['nodes'] if n['type']==kind and n['boundsInScreen']==box and n['role']!='prototype-hotspot']
  if len(found)!=1:raise SystemExit(f'Review {screen} {box}: expected one, got {len(found)}')
  return found[0]
 heroes=[one(s,'rectangle',[24,140,342,138]) for s in docs]
 one('U35','rectangle',[24,334,342,52]);one('U35','rectangle',[24,445,342,52])
 one('U36','rectangle',[24,334,342,52]);one('U36','rectangle',[24,424,342,82])
 one('U37','rectangle',[24,320,342,82]);one('U37','rectangle',[24,420,342,82])
 text=one('U35','text',[45,218.89,241,30])
 values={'heroMinHeight':heroes[0]['boundsInScreen'][3],'heroTitleFontSize':text['style']['font_size'],'heroTitleLineHeight':1.5,'heroIconTextGap':14,'fieldMinHeight':52,'labelFieldGap':9,'groupFieldMembersGap':38,'multiHeroBottomGap':42,'multiRowBottomGap':18,'multiNoteTopGap':23}
 content='// Generated by tools/design/generate_commerce_metrics.py; do not edit.\n// Native source SHA256: '+sha+'\n// Responsive reviewed flow mapping; no absolute text positioning.\nabstract final class FigCraftCommerceMetrics {\n'+''.join(f'  static const double {k} = {v:g};\n' for k,v in values.items())+'}\n'
 target=ROOT/'packages/mobile_shared/lib/presentation/figcraft_commerce_metrics.dart'
 if args.check:
  if not target.exists() or target.read_text()!=content:raise SystemExit('Stale generated commerce metrics')
 else:target.write_text(content)
 print(json.dumps({'status':'PASS','screens':list(docs),'masterSha256':sha,'check':args.check}))
if __name__=='__main__':main()
