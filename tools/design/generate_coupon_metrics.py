#!/usr/bin/env python3
"""Generate reviewed U26 style metrics from pinned IR; no fixture copy in Dart."""
import argparse,json,hashlib
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
 ir=json.loads((ROOT/'design/figcraft/reports/layout-ir/U26.json').read_text());mapping=json.loads((ROOT/'design/figcraft/handoff/component-mappings/U26.json').read_text())
 sha=hashlib.sha256((ROOT/'design/figcraft/BitPOS-Platform-UI.figcraft').read_bytes()).hexdigest()
 if sha!=ir['masterSha256']:raise SystemExit('STALE U26 IR; extract current master before generation')
 selected={}
 for role,selector in mapping['selectors'].items():
  found=[n for n in ir['nodes'] if n['type']==selector['type'] and ('boundsInScreen' not in selector or n['boundsInScreen']==selector['boundsInScreen']) and ('fontSize' not in selector or n.get('style',{}).get('font_size')==selector['fontSize']) and ('text' not in selector or n.get('characters')==selector['text'])]
  if len(found)!=1:raise SystemExit(f'Review mapping {role}: expected1node, got{len(found)}')
  selected[role]=found[0]
 h=selected['hero'];title=selected['title'];amount=selected['amount'];subtitle=selected['subtitle']
 values={'heroMinHeight':h['boundsInScreen'][3],'heroPadding':title['boundsInScreen'][0]-h['boundsInScreen'][0],'titleFontSize':title['style']['font_size'],'amountFontSize':amount['style']['font_size'],'subtitleFontSize':subtitle['style']['font_size']}
 # Native text bounds include different font ascent offsets; reviewed flow gaps
 # use baseline sizes and preserve the151px envelope at the standard text scale.
 values.update(mapping['reviewedFlowSpacing'])
 content='// Generated by tools/design/generate_coupon_metrics.py; do not edit.\n// Native source SHA256: '+sha+'\nabstract final class FigCraftCouponMetrics {\n'+''.join(f'  static const double {k} = {v:g};\n' for k,v in values.items())+'}\n'
 target=ROOT/'packages/mobile_shared/lib/presentation/figcraft_coupon_metrics.dart'
 if a.check:
  if not target.exists() or target.read_text()!=content:raise SystemExit('Generated coupon metrics are stale')
 else:target.write_text(content)
 print(json.dumps({'status':'PASS','masterSha256':sha,'mappedNodes':{k:v['id'] for k,v in selected.items()},'metrics':values,'check':a.check}))
if __name__=='__main__':main()
