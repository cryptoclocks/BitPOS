#!/usr/bin/env python3
"""Reviewed R07/WD01 geometry mapping; emit styles, never controllers or fixture facts."""
import json,hashlib,argparse
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();sha=hashlib.sha256((ROOT/'design/figcraft/BitPOS-Platform-UI.figcraft').read_bytes()).hexdigest()
 def load(screen):
  ir=json.loads((ROOT/f'design/figcraft/reports/layout-ir/{screen}.json').read_text())
  if ir['masterSha256']!=sha:raise SystemExit('Stale IR: '+screen)
  return ir
 def shape(ir,box):
  matches=[n for n in ir['nodes'] if n['type']=='rectangle' and n['boundsInScreen']==box and n['role']!='prototype-hotspot']
  if len(matches)!=1:raise SystemExit('Review shape mapping: '+str(box))
  return matches[0]
 rider=load('R07');panel=shape(rider,[0,348,390,496]);accept=shape(rider,[24,715,342,52]);pad=accept['boundsInScreen'][0]-panel['boundsInScreen'][0];radius=panel['corners']['radii'][0]
 pay=load('WD01');left=shape(pay,[96,210,744,680]);right=shape(pay,[872,210,472,680]);lx,ly,lw,lh=left['boundsInScreen'];rx,ry,rw,rh=right['boundsInScreen'];gap=rx-lx-lw
 files={ROOT/'apps/mobile-driver/lib/presentation/figcraft_offer_metrics.dart':f'''// Generated by tools/design/generate_surface_metrics.py; do not edit.
// Native SHA256: {sha}
abstract final class FigCraftOfferMetrics {{
  static const double padding = {pad:g};
  static const double radius = {radius:g};
  static const double actionHeight = {accept['boundsInScreen'][3]:g};
}}
''',ROOT/'apps/web/src/styles/figcraft-checkout-metrics.css':f'''/* Generated from reviewed WD01 native geometry. SHA256: {sha} */
.customer-checkout{{
 --bp-checkout-workspace:{lw+rw+gap:g}px;
 --bp-checkout-summary-weight:{lw:g}fr;
 --bp-checkout-payment-weight:{rw:g}fr;
 --bp-checkout-gap:{gap:g}px;
 --bp-checkout-card-min-height:{min(lh,rh):g}px;
 --bp-checkout-card-radius:{left['corners']['radii'][0]:g}px;
}}
'''}
 for path,content in files.items():
  if args.check:
   if not path.exists() or path.read_text()!=content:raise SystemExit('Stale generated output: '+str(path))
  else:path.write_text(content)
 print(json.dumps({'status':'PASS','masterSha256':sha,'mappedNodes':[panel['id'],accept['id'],left['id'],right['id']],'files':[str(p.relative_to(ROOT)) for p in files],'check':args.check}))
if __name__=='__main__':main()
