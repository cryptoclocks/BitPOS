def run(cmds, a, b):
    open('pl-run.json', 'w').write(json.dumps(cmds, ensure_ascii=False))
    out = subprocess.run([CLI, 'run', 'pl-run.json', '--in', a, '--out', b], capture_output=True, text=True).stdout.strip().split('\n')
    return [json.loads(l) for l in out if l.startswith('{')]

def tree(a, fid):
    open('pl-get.json', 'w').write(json.dumps([{"command": "node.get", "params": {"id": fid, "depth": 30}}]))
    out = subprocess.run([CLI, 'run', 'pl-get.json', '--in', a], capture_output=True, text=True).stdout.strip().split('\n')[-1]
    return json.loads(out)['result']

