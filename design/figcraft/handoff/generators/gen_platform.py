for k, (name, title, sub, cols, rows) in enumerate(FR):
    nxt = 'pl-%d.figcraft' % k
    fid = run([{"command": "edit.duplicate", "params": {"ids": [6758]}}], cur, nxt)[0]['result']['ids'][0]
    t = tree(nxt, fid)
    texts = []
    def walk(o):
        if isinstance(o, dict):
            if o.get('type') == 'TEXT': texts.append(o)
            for v in o.values(): walk(v)
        elif isinstance(o, list):
            for v in o: walk(v)
    walk(t)
    body = sorted([x for x in texts if x['x'] > 250 and 90 < x['y'] < 800], key=lambda x: (round(x['y']), x['x']))
    side = sorted([x for x in texts if 60 < x['x'] < 70 and 150 < x['y'] < 780], key=lambda x: x['y'])
    cmds = [{"command": "node.set", "params": {"ids": [fid], "name": name}}]
    def sc(node, s): cmds.append({"command": "node.set", "params": {"ids": [node['id']], "characters": s}})
    vals = [title, sub, 'ทั้งหมด', 'ตัวกรอง', '3 รายการตัวอย่าง'] + list(cols) + [c for r in rows for c in r]
